#!/usr/bin/env node
/* ═══════════════════════════════════════════════════════════════════════════
   MōdSynth — single-file build
   ───────────────────────────────────────────────────────────────────────────
   Inlines the stylesheet and every script into one HTML file that runs with no
   server at all — straight off the filesystem, from a USB stick, or inside an
   embedded browser view.

   The one thing that can't just be concatenated is the audio worklet.
   `audioWorklet.addModule()` needs a URL, and under file:// there's no origin
   to fetch from. So the DSP source is embedded as a string and the engine
   turns it into a blob: URL at startup — see loadWorkletModule() in
   js/engine.js, which already prefers `MS_DSP_SOURCE` when it exists.

   Run: node tools/build-standalone.js
   ═══════════════════════════════════════════════════════════════════════════ */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'modsynth-standalone.html');

const read = rel => fs.readFileSync(path.join(ROOT, rel), 'utf8');

function main() {
  let html = read('index.html');

  const css = read('css/modsynth.css');
  html = html.replace(
    /<link rel="stylesheet" href="css\/modsynth\.css">/,
    '<style>\n' + css + '\n</style>'
  );

  // Scripts, in the order index.html loads them.
  const scripts = (html.match(/<script src="js\/[^"]+"><\/script>/g) || [])
    .map(tag => tag.match(/src="(js\/[^"]+)"/)[1]);
  if (!scripts.length) throw new Error('no script tags found in index.html');

  const dsp = read('js/dsp.js');
  // JSON.stringify handles every escaping case, including any backtick or
  // backslash the DSP source might grow later.
  const dspBlock =
    '<script>\n' +
    '/* The audio worklet source, embedded so it can be loaded from a blob URL\n' +
    '   without a fetch — which is what makes this file work under file://. */\n' +
    'window.MS_DSP_SOURCE = ' + JSON.stringify(dsp) + ';\n' +
    '</script>';

  const bundle = scripts.map(rel => {
    return '<script>\n/* ═══ ' + rel + ' ═══ */\n' + read(rel) + '\n</script>';
  }).join('\n');

  // Replace the first script tag with everything, and drop the rest.
  html = html.replace(/<script src="js\/[^"]+"><\/script>\s*/g, '');
  html = html.replace('</body>', dspBlock + '\n' + bundle + '\n</body>');

  // The engine's default dspUrl is only a fallback now, but point it at
  // nothing sensible-looking so a failure is obvious rather than mysterious.
  html = html.replace(
    "<title>MōdSynth</title>",
    "<title>MōdSynth</title>\n<!-- Single-file build. Generated by tools/build-standalone.js — do not edit; rebuild. -->"
  );

  fs.writeFileSync(OUT, html);

  const kb = (Buffer.byteLength(html) / 1024).toFixed(0);
  console.log('Built modsynth-standalone.html');
  console.log('  ' + scripts.length + ' scripts + stylesheet + worklet source inlined');
  console.log('  ' + kb + ' KB, no external requests');

  // Cheap structural check: everything that should be gone is gone, and
  // everything that should be present is present.
  const problems = [];
  if (/<script src=/.test(html)) problems.push('an external script survived');
  if (/<link rel="stylesheet"/.test(html)) problems.push('an external stylesheet survived');
  if (!/MS_DSP_SOURCE/.test(html)) problems.push('the worklet source is missing');
  if (!/registerProcessor/.test(html)) problems.push('the DSP body is missing');
  scripts.forEach(rel => {
    const marker = '═══ ' + rel + ' ═══';
    if (!html.includes(marker)) problems.push('missing ' + rel);
  });
  if (problems.length) {
    console.error('  problems: ' + problems.join(', '));
    process.exit(1);
  }
  console.log('  verified: no external requests remain, all scripts inlined');
}

if (require.main === module) main();
