/* Records the EQ's reference responses from the browser's own filters.
   Run (needs Chrome; nothing else): node tests/eq/record-refs.js

   Opens tests/eq/eqref.html in headless Chrome, which builds each case out of
   BiquadFilterNodes and asks them for getFrequencyResponse, and writes what it
   prints to tests/eq/refs.json (the node tests read it) and native/modsynth/eqref.h
   (eqtest.cpp includes it). Both are committed; this only needs re-running when
   the cases in eqref.html change or when a browser changes what its filters do. */
'use strict';
const { execFileSync } = require('child_process');
const fs = require('fs'), os = require('os'), path = require('path');
const CHROME = process.env.CHROME || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const page = path.join(__dirname, 'eqref.html');
const prof = fs.mkdtempSync(path.join(os.tmpdir(), 'eqref-'));
const dom = execFileSync(CHROME, ['--headless=new', '--disable-gpu', '--no-first-run', '--user-data-dir=' + prof,
  '--virtual-time-budget=5000', '--dump-dom', 'file://' + page], { encoding: 'utf8', maxBuffer: 1 << 24 });
fs.rmSync(prof, { recursive: true, force: true });
const m = dom.match(/EQREF([\s\S]*?)EQREF/);
if (!m) throw new Error('no EQREF block in the page output');
const data = JSON.parse(m[1].replace(/&quot;/g, '"').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>'));
data.chrome = execFileSync(CHROME, ['--version'], { encoding: 'utf8' }).trim();
fs.writeFileSync(path.join(__dirname, 'refs.json'), '{"chrome":' + JSON.stringify(data.chrome) + ',"freqs":' + JSON.stringify(data.freqs)
  + ',"cases":[\n' + data.cases.map(c => JSON.stringify(c)).join(',\n') + '\n]}\n');

// The C++ side: the same cases as a table. Keys in the order of K, so eqtest reads
// them by position.
const K = ['lo', 'mid', 'midHz', 'hi', 'loHz', 'hiHz', 'midQ', 'hpfOn', 'hpfHz', 'hpfQ', 'hpfSlope', 'lpfOn', 'lpfHz', 'lpfQ', 'lpfSlope', 'mid2', 'mid2Hz', 'mid2Q'];
const n = x => (Number.isInteger(x) ? x + '.0' : String(x));
let h = '// Generated by tests/eq/record-refs.js from ' + data.chrome + ': do not edit.\n'
  + '// BiquadFilterNode.getFrequencyResponse for the EQ cases in tests/eq/eqref.html, in dB.\n'
  + '// Model order: lo, mid, midHz, hi, loHz, hiHz, midQ, hpfOn, hpfHz, hpfQ, hpfSlope,\n'
  + '// lpfOn, lpfHz, lpfQ, lpfSlope, mid2, mid2Hz, mid2Q.\n#pragma once\n'
  + 'static const int EQREF_NF = ' + data.freqs.length + ';\nstatic const double EQREF_F[EQREF_NF] = {' + data.freqs.join(', ') + '};\n'
  + 'struct EqRefCase { const char* name; double sr; double m[' + K.length + ']; double db[EQREF_NF]; };\n'
  + 'static const int EQREF_N = ' + data.cases.length + ';\nstatic const EqRefCase EQREF[EQREF_N] = {\n';
for (const c of data.cases)
  h += '  {"' + c.name + '", ' + n(c.sr) + ', {' + K.map(k => n(c.model[k])).join(', ') + '}, {' + c.db.map(n).join(', ') + '}},\n';
h += '};\n';
fs.writeFileSync(path.join(__dirname, '../../native/modsynth/eqref.h'), h);
console.log('recorded ' + data.cases.length + ' cases from ' + data.chrome);
